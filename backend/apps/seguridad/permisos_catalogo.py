@dataclass(frozen=True, slots=True)
class PermisoDef:
    codigo: str
    descripcion: str
    critico: bool = False

    @property
    def modulo(self) -> str:
        return self.codigo.split(".", 1)[0]

    @property
    def accion(self) -> str:
        return self.codigo.rsplit(".", 1)[-1]


def _p(codigo: str, descripcion: str, critico: bool = False) -> PermisoDef:
    return PermisoDef(codigo, descripcion, critico)


