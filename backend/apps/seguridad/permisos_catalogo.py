class RolDef:
    codigo: str
    nombre: str
    descripcion: str
    es_sistema: bool = False
    es_critico: bool = False
    # codigo de permiso -> alcance. "*" = todos los permisos del catálogo.
    permisos: dict[str, str] = field(default_factory=dict)


def _todos(alcance: str, excepto: tuple[str, ...] = ()) -> dict[str, str]:
    return {c: alcance for c in sorted(CODIGOS) if c not in excepto}


